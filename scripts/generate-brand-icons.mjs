// Generates src/app/cv/brandIcons.ts with the official logos used by the sample CV.
// Icons come from the Iconify "logos" set (CC0). Run: node scripts/generate-brand-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const set = JSON.parse(readFileSync(new URL('../node_modules/@iconify-json/logos/icons.json', import.meta.url)));
const wanted = {
  figma: 'figma',
  adobe: 'adobe-icon',
  chatgpt: 'openai-icon',
  midjourney: 'midjourney',
  linear: 'linear-icon',
  notion: 'notion-icon',
  productboard: 'productboard-icon',
  hotjar: 'hotjar-icon',
  strapi: 'strapi-icon',
};

function toDataUrl(name) {
  const icon = set.icons[name];
  if (!icon) throw new Error(`Missing icon ${name}`);
  const w = icon.width ?? set.width ?? 16;
  const h = icon.height ?? set.height ?? 16;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${icon.left ?? 0} ${icon.top ?? 0} ${w} ${h}">${icon.body}</svg>`;
  return 'data:image/svg+xml;utf8,' + encodeURIComponent(svg);
}

const lines = Object.entries(wanted).map(([key, name]) => `  ${key}: '${toDataUrl(name)}',`);
writeFileSync(
  new URL('../src/app/cv/brandIcons.ts', import.meta.url),
  `// Generated by scripts/generate-brand-icons.mjs from the Iconify "logos" set (CC0). Do not edit by hand.\nexport const brandIcons = {\n${lines.join('\n')}\n} as const;\n`,
);
