"""Fetch every Fontshare family usable as a CV title font, in one bold weight.

Keeps families that have a 600-800 weight (closest to 700) and cover every letter the 7 interface
languages need; skips script and handwriting faces. Writes:
  public/fonts/titles/<slug>.woff2 / .ttf   the bold file (pages / designed PDF)
  public/fonts/titles/CREDITS.txt           family, publisher and license of each font
  src/app/titleFonts.ts                     the list the Typefaces menu shows

Run from the repo root (needs network access to api.fontshare.com and cdn.fontshare.com, and fontTools):
  python3 -I scripts/fontshare/fetch_title_fonts.py
"""
import json, os, re, subprocess, sys, time
from fontTools.ttLib import TTFont

ROOT = os.getcwd()
OUT = os.path.join(ROOT, 'public/fonts/titles')
TS = os.path.join(ROOT, 'src/app/titleFonts.ts')
API = 'https://api.fontshare.com/v2'
SKIP_CATEGORIES = ('script', 'handwritten')
LICENSES = {'itf_ffl': 'ITF Free Font License', 'sil_ofl': 'SIL Open Font License 1.1'}
LOWER = 'àèéìòùáíóúâêîôûäëïöüÿçñãõßœæ'
NEED = LOWER + LOWER.replace('ß', '').upper() + '’“”«»–—€…·'


def fetch(url, out=None):
    for attempt in range(8):
        cmd = ['curl', '-sS', '-f', '-m', '60', '--http1.1', url]
        if out:
            cmd[1:1] = ['-o', out]
        r = subprocess.run(cmd, capture_output=True)
        if r.returncode == 0:
            return r.stdout if not out else None
        time.sleep(1.5 * (attempt + 1))
    raise RuntimeError(f'could not fetch {url}')


def weights(family):
    out = set()
    for s in family.get('styles', []):
        w = s.get('weight')
        w = w.get('weight') if isinstance(w, dict) else w
        if s.get('is_italic') or s.get('is_variable'):
            continue
        if isinstance(w, int):
            out.add(w)
    return out


def category(family):
    c = (family.get('category') or '').lower()
    for name in ('serif', 'slab', 'display', 'sans'):
        if name in c.split(',')[0].strip() or c.startswith(name):
            return name
    return 'display'


def main():
    os.makedirs(OUT, exist_ok=True)
    families = json.loads(fetch(f'{API}/fonts?limit=200'))['fonts']
    kept, report = [], []
    for f in sorted(families, key=lambda f: f['name'].lower()):
        slug, name = f['slug'], f['name']
        cat = (f.get('category') or '').lower()
        if any(s in cat for s in SKIP_CATEGORIES):
            report.append(f'skip {name}: {f["category"]} face')
            continue
        ws = weights(f)
        pick = next((w for w in (700, 600, 800) if w in ws), None)
        if pick is None:
            report.append(f'skip {name}: no 600-800 weight (has {sorted(ws)})')
            continue
        css = fetch(f'{API}/css?f[]={slug}@{pick}&display=swap').decode()
        woff2 = re.search(r"url\('(//[^']+\.woff2)'\)", css)
        ttf = re.search(r"url\('(//[^']+\.ttf)'\)", css)
        if not (woff2 and ttf):
            report.append(f'skip {name}: no woff2/ttf files')
            continue
        ttf_path, woff2_path = f'{OUT}/{slug}.ttf', f'{OUT}/{slug}.woff2'
        fetch('https:' + ttf.group(1), ttf_path)
        cmap = TTFont(ttf_path).getBestCmap()
        missing = ''.join(c for c in NEED if ord(c) not in cmap)
        if missing:
            os.remove(ttf_path)
            report.append(f'skip {name}: missing {missing}')
            continue
        fetch('https:' + woff2.group(1), woff2_path)
        designers = ', '.join(d.get('name') for d in f.get('designers') or [] if d.get('name'))
        kept.append({
            'slug': slug, 'name': name, 'category': category(f), 'weight': pick,
            'license': LICENSES.get(f.get('license_type'), f.get('license_type') or 'see fontshare.com'),
            'designers': designers or 'Indian Type Foundry',
        })
        report.append(f'keep {name} ({pick})')

    with open(TS, 'w') as t:
        t.write('// Generated by scripts/fontshare/fetch_title_fonts.py. Do not edit by hand.\n')
        t.write('// Fontshare families usable for CV titles, each as one bold file in public/fonts/titles.\n')
        t.write("export type TitleCategory = 'sans' | 'serif' | 'display' | 'slab';\n")
        t.write('export interface TitleFont {\n  slug: string;\n  name: string;\n  category: TitleCategory;\n  weight: number;\n}\n\n')
        t.write('export const titleFonts: TitleFont[] = [\n')
        for k in kept:
            t.write(f"  {{ slug: {json.dumps(k['slug'])}, name: {json.dumps(k['name'])}, category: '{k['category']}', weight: {k['weight']} }},\n")
        t.write('];\n')
    with open(f'{OUT}/CREDITS.txt', 'w') as c:
        c.write('Title fonts, downloaded from Fontshare (https://www.fontshare.com) by\n')
        c.write('scripts/fontshare/fetch_title_fonts.py. Each family keeps its own license:\n')
        c.write('the ITF Free Font License (https://fontshare.com/terms) or the SIL Open Font License 1.1\n')
        c.write('(https://openfontlicense.org). Each line: family (weight used), designers, license.\n\n')
        for k in kept:
            c.write(f"{k['name']} ({k['weight']}): {k['designers']}. {k['license']}.\n")
    print('\n'.join(report))
    print(f'\n{len(kept)} kept of {len(families)}')


if __name__ == '__main__':
    sys.exit(main())
